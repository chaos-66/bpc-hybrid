"""Build or verify the deterministic S2.3 public marker lexicon artifacts."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


FORMAL_ROOT = Path(__file__).resolve().parents[1]
SRC = FORMAL_ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from bpc_hybrid.sun_style.public_marker_lexicon import (  # noqa: E402
    PublicMarkerLexiconError,
    materialize_or_check,
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--check",
        action="store_true",
        help="Verify exact generated bytes without writing.",
    )
    mode.add_argument(
        "--write",
        action="store_true",
        help="Write missing versioned artifacts; never overwrite differing bytes.",
    )
    args = parser.parse_args()
    try:
        report = materialize_or_check(FORMAL_ROOT, write=args.write)
    except PublicMarkerLexiconError as exc:
        print(f"S2.3 public marker lexicon failed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
